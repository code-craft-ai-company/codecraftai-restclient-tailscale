def class_name_for_schema(*, schema_name: str) -> str:
    """
        Compute the emitted Python class name for an OpenAPI schema name.

        :param schema_name: The schema key from ``components/schemas``.

        :returns: A ``Tailscale``-prefixed PascalCase class name.
    """
    cleaned = schema_name.replace("_", " ").replace("-", " ")
    parts = cleaned.split()
    pascal_parts: List[str] = []
    for part in parts:
        if len(part) == 0:
            continue
        pascal_parts.append(part[0].upper() + part[1:])

    joined = "".join(pascal_parts)
    rtnval = "Tailscale{}".format(joined)
    return rtnval


def module_name_for_class(*, class_name: str) -> str:
    """
        Compute the lowercase-no-underscore module file stem for a class.

        :param class_name: The emitted Python class name.

        :returns: The module file stem (no ``.py`` suffix).
    """
    rtnval = class_name.lower()
    return rtnval


def _emit_field_line(*, field_name: str, field_schema: Dict[str, Any],
                     required: bool) -> str:
    """
        Build a single ``Field`` assignment source line for a schema property.

        :param field_name: The OpenAPI property name.
        :param field_schema: The OpenAPI schema fragment for the property.
        :param required: Whether the property is in the schema ``required``
            list.

        :returns: A single line of Python source.
    """
    py_type = python_type_for_schema(schema=field_schema)

    description = field_schema.get("description")
    desc_arg = ""
    if description is not None:
        flat = " ".join(description.split())
        safe = flat.replace('"', "'")
        desc_arg = ', description="{}"'.format(safe)

    if required is True:
        rtnval = '    {} = Field({}, required=True{})'.format(
            field_name, py_type, desc_arg)
        return rtnval

    rtnval = '    {} = Field(Optional[{}], required=False, default=None{})'.format(
        field_name, py_type, desc_arg)
    return rtnval


def emit_schema_module(*, schema_name: str,
                        schema: Dict[str, Any]) -> Tuple[str, str, str]:
    """
        Emit the Python source for one OpenAPI schema.

        :param schema_name: The schema key from ``components/schemas``.
        :param schema: The OpenAPI schema fragment dictionary.

        :returns: A tuple of ``(class_name, module_name, source_text)``.
    """
    class_name = class_name_for_schema(schema_name=schema_name)
    module_name = module_name_for_class(class_name=class_name)

    lines: List[str] = []
    lines.append(GENERATED_HEADER.format(module_name=module_name))
    lines.append("")
    lines.append("")
    lines.append("class {}(SchemaObject):".format(class_name))

    description = schema.get("description")
    doc_summary = "Auto-generated from Tailscale OpenAPI schema '{}'.".format(
        schema_name)
    lines.append('    """')
    lines.append("        {}".format(doc_summary))
    if description is not None:
        flat = " ".join(description.split())
        lines.append("")
        lines.append("        {}".format(flat))
    lines.append('    """')

    properties = schema.get("properties")
    required_list = schema.get("required")
    if required_list is None:
        required_list = []

    if properties is None or len(properties) == 0:
        lines.append("")
        lines.append("    pass")
    else:
        lines.append("")
        # Stable, deterministic ordering: required first then alphabetical.
        ordered_names = sorted(
            properties.keys(),
            key=lambda name: (0 if name in required_list else 1, name))
        for prop_name in ordered_names:
            prop_schema = properties[prop_name]
            is_required = prop_name in required_list
            field_line = _emit_field_line(field_name=prop_name,
                                          field_schema=prop_schema,
                                          required=is_required)
            lines.append(field_line)

    lines.append("")
    source_text = os.linesep.join(lines)
    rtnval = (class_name, module_name, source_text)
    return rtnval


def emit_all_schemas(*, schemas: Dict[str, Any]) -> Dict[str, Tuple[str, str]]:
    """
        Emit Python source for every object schema in a schemas section.

        :param schemas: The ``components/schemas`` dictionary.

        :returns: A mapping of ``module_name`` to ``(class_name, source)``.
    """
    rtnval: Dict[str, Tuple[str, str]] = {}

    for schema_name in sorted(schemas.keys()):
        schema = schemas[schema_name]
        if not isinstance(schema, dict):
            continue

        declared_type = schema.get("type")
        has_props = "properties" in schema
        has_allof = "allOf" in schema

        # Only object-shaped schemas become model classes. Scalar/enum
        # aliases (string, array) are not emitted as classes.
        if declared_type != "object" and not has_props and not has_allof:
            continue

        class_name, module_name, source_text = emit_schema_module(
            schema_name=schema_name, schema=schema)
        rtnval[module_name] = (class_name, source_text)

    return rtnval


def emit_model_init(*, emitted: Dict[str, Tuple[str, str]]) -> str:
    """
        Emit the ``model/__init__.py`` re-export source.

        :param emitted: The mapping produced by :func:`emit_all_schemas`.

        :returns: The ``__init__.py`` source text.
    """
    lines: List[str] = []
    lines.append('"""')
    lines.append("    .. module:: model")
    lines.append("        :synopsis: Re-exports for the generated Tailscale "
                 "OpenAPI model classes.")
    lines.append("")
    lines.append("    DO NOT EDIT BY HAND. Regenerate via")
    lines.append("    ``python -m automojo.restclient.tailscale._codegen."
                 "import_openapi``.")
    lines.append('"""')
    lines.append("")

    all_names: List[str] = []
    for module_name in sorted(emitted.keys()):
        class_name, _ = emitted[module_name]
        all_names.append(class_name)
        lines.append("from automojo.restclient.tailscale.model.{} import {}".format(
            module_name, class_name))

    lines.append("")
    lines.append("__all__ = [")
    for class_name in sorted(all_names):
        lines.append('    "{}",'.format(class_name))
    lines.append("]")
    lines.append("")

    rtnval = os.linesep.join(lines)
    return rtnval
